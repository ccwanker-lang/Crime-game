    ("leaf_dark", (0.24, 0.47, 0.23)), ("leaf", (0.37, 0.62, 0.27)), ("leaf_light", (0.57, 0.74, 0.31)),
    ("bark", (0.43, 0.30, 0.21)), ("hill", (0.56, 0.69, 0.50)),
    # objects, metal, wood, glass, light, accents
    ("metal_dark", (0.21, 0.22, 0.24)), ("metal", (0.60, 0.62, 0.65)), ("wood", (0.66, 0.45, 0.28)),
