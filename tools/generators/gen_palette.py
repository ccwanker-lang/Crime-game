    ("plaster_blue", (0.62, 0.74, 0.80)), ("plaster_green", (0.69, 0.78, 0.60)),
    # roofs, trim, doors
    ("roof_red", (0.79, 0.40, 0.25)), ("roof_dark", (0.29, 0.31, 0.38)), ("roof_slate", (0.43, 0.47, 0.53)),
    ("trim_white", (0.96, 0.95, 0.91)), ("trim_dark", (0.17, 0.18, 0.21)), ("door_green", (0.17, 0.42, 0.32)),
    ("door_blue", (0.19, 0.29, 0.50)), ("door_red", (0.66, 0.20, 0.17)),
